# Build data/econ494.js for the site from the ECON 494 assignments.
#
#   Assignment 4 ("I Just Ran Two Million Regressions"): Sala-i-Martin's growth
#   data (BMS::datafls). One regression per candidate variable, then all 7,770
#   regressions for RuleofLaw with every possible set of three controls.
#   Assignment 3 ("Recessions and Emissions"): CO2 per person against GDP per
#   person for every country, from the World Bank (WDI), every year from 2000.
#
# Run from the portfolio folder:  Rscript scripts/build_econ494.R

suppressPackageStartupMessages({
  library(tidyverse)
  library(broom)
  library(jsonlite)
  library(WDI)
})

data("datafls", package = "BMS")
growth <- as_tibble(datafls)
fixed  <- c("GDP60", "LifeExp", "PrScEnroll")
my_var <- "RuleofLaw"

## Q1: one regression per candidate ------------------------------------
q1 <- growth |>
  pivot_longer(-c(y, all_of(fixed)), names_to = "variable", values_to = "value") |>
  group_by(variable) |>
  nest() |>
  mutate(t = map_dbl(data, \(d) tidy(lm(y ~ GDP60 + LifeExp + PrScEnroll + value, data = d)) |>
                         filter(term == "value") |> pull(statistic))) |>
  select(variable, t) |>
  arrange(t) |>
  ungroup()

## Q2: 7,770 regressions ----------------------------------------------
others  <- setdiff(names(growth), c("y", fixed, my_var))
triples <- combn(others, 3, simplify = FALSE)
fit_one <- function(controls) {
  f <- reformulate(c(fixed, my_var, controls), response = "y")
  s <- summary(lm(f, data = growth))$coefficients
  c(s[my_var, "Estimate"], s[my_var, "t value"])
}
res <- do.call(rbind, lapply(triples, fit_one))
cat("regressions:", nrow(res), " share positive:", mean(res[, 1] > 0),
    " share |t|>1.96:", mean(abs(res[, 2]) > 1.96), "\n")

## Assignment 3: emissions and income ---------------------------------
wdi <- WDI(
  indicator = c(co2 = "EN.GHG.CO2.PC.CE.AR5", gdp = "NY.GDP.PCAP.PP.KD", pop = "SP.POP.TOTL"),
  country = "all", start = 2000, end = 2026, extra = TRUE
) |>
  filter(!is.na(region), region != "Aggregates") |>
  select(iso = iso3c, country, region, year, co2, gdp, pop) |>
  drop_na() |>
  filter(co2 > 0)

years <- sort(unique(wdi$year))
countries <- wdi |>
  arrange(iso, year) |>
  group_by(iso, country, region) |>
  summarise(series = list(map2(year, seq_along(year), \(yr, i) c(yr, round(gdp[i]), signif(co2[i], 3), pop[i]))),
            .groups = "drop") |>
  filter(lengths(series) >= length(years) - 2)

out <- list(
  q1 = q1 |> mutate(t = round(t, 3)),
  q2 = list(variable = my_var, est = signif(res[, 1], 4), t = round(res[, 2], 3)),
  wdi = list(years = years, countries = countries)
)
writeLines(
  c("/* Generated by scripts/build_econ494.R from the ECON 494 assignments. */",
    paste0("window.E494 = ", toJSON(out, auto_unbox = TRUE, digits = NA), ";")),
  "data/econ494.js"
)
cat("wrote data/econ494.js;", nrow(countries), "countries,", min(years), "-", max(years), "\n")
